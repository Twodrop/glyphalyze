/**
 * Matches text ending with an abbreviation that is usually followed by more of the same sentence,
 * such as "Mr. ". Spaces may follow, but not a line break.
 */
const ENDS_WITH_ABBREVIATION = /\b(?:Mr|Mrs|Ms|Dr|Prof|Rev|Capt|Gen|Lt|Col|Sgt|e\.g|i\.e)\.[^\S\n\r]*$/

/**
 * Splits text into words, characters and sentences using Intl.Segmenter.
 */
export class Tokenizer {
  readonly #wordSegmenter = new Intl.Segmenter('en', { granularity: 'word' })
  readonly #charSegmenter = new Intl.Segmenter('en', { granularity: 'grapheme' })
  readonly #sentenceSegmenter = new Intl.Segmenter('en', { granularity: 'sentence' })

  /**
   * Cleans up a text and splits it into words.
   *
   * @example
   * new Tokenizer().getWords('Hello, how\n are you?') // Returns ['Hello', 'how', 'are', 'you']
   * @param text - The text to clean up.
   * @returns The words in the text, cleaned up.
   */
  getWords(text: string): string[] {
    const words: string[] = []
    const segmentedWords = this.#wordSegmenter.segment(text)

    // Only adds elements deemed "word-like" by the segmenter.
    for (const element of segmentedWords) {
      if (element.isWordLike) {
        words.push(element.segment)
      }
    }
    return words
  }

  /**
   * Splits a text into characters.
   * Emojis count as one character, instead of one per Unicode code unit.
   * Includes line breaks and spaces.
   *
   * @example
   * new Tokenizer().getCharacters('Hi 👍🏽') // Returns ['H', 'i', ' ', '👍🏽']
   * @param text - The text to clean up.
   * @returns The characters in the text, cleaned up.
   */
  getCharacters(text: string): string[] {
    const characters: string[] = []
    const segmentedCharacters = this.#charSegmenter.segment(text)

    for (const element of segmentedCharacters) {
      characters.push(element.segment)
    }
    return characters
  }

  /**
   * Splits a text into sentences.
   * A single line break does not end a sentence, but an empty line does.
   * Abbreviations such as "Mr." or "e.g." do not end a sentence.
   *
   * @example
   * new Tokenizer().getSentences('Hello sir! How are you today?')
   * // Returns ['Hello sir! ', 'How are you today?']
   * @param text - The text to split up.
   * @returns The sentences in the text, split up.
   */
  getSentences(text: string): string[] {
    const sentences: string[] = []
    const segmentedSentences = this.#sentenceSegmenter.segment(this.#hideSingleLineBreaks(text))
    let previousEndsWithAbbreviation = false

    // Slices the original text, so the hidden line breaks are kept in the sentences.
    // Generated by Claude Opus 5.5 High
    for (const element of segmentedSentences) {
      const sentence = text.slice(element.index, element.index + element.segment.length)
      const last = sentences.length - 1

      // Whitespace-only segments (from empty lines) and segments following an abbreviation
      // are merged instead of counted as sentences.
      if (last >= 0 && (previousEndsWithAbbreviation || sentence.trim() === '' || sentences[last].trim() === '')) {
        sentences[last] += sentence
      } else {
        sentences.push(sentence)
      }

      // Checks the segment with hidden line breaks, so only an empty line after an abbreviation ends the sentence.
      previousEndsWithAbbreviation = ENDS_WITH_ABBREVIATION.test(element.segment)
    }
    return sentences
  }

  /**
   * Replaces each single line break with spaces of the same length,
   * since the sentence segmenter treats every line break as the end of a sentence.
   * Line breaks next to another line break (an empty line) are left as they are.
   * Generated by Claude Opus 5.5 High
   *
   * @param text - The text to modify.
   * @returns The text without single line breaks.
   */
  #hideSingleLineBreaks(text: string): string {
    return text.replace(/(?<![\n\r][^\S\n\r]*)(?:\r\n|[\n\r])(?![^\S\n\r]*[\n\r])/g, (lineBreak) =>
      ' '.repeat(lineBreak.length)
    )
  }
}
